import { sql, type SQLWrapper } from '@aibot/db';

/**
 * ★ **البحثُ عن زبونٍ — قطعةٌ واحدةٌ تخدم الإنبوكس وجهات الاتّصال معاً.**
 *
 *   العطلُ الذي وُلدت منه: كلُّ شاشةٍ كتبت بحثَها. فجهاتُ الاتّصال تُطابق
 *   ذيلَ الرقم وتُهرّب محارف البدل، والإنبوكس يفعل لا هذا ولا ذاك — فبحث
 *   «0791234567» لا يجد `962791234567` في الإنبوكس ويجده في جهات الاتّصال،
 *   وبحث «50%» في الإنبوكس **يُطابق كلّ شيء**. والموظّف الذي يتلقّى مكالمةً
 *   من زبون ويريد فتح محادثته يفشل في نصف الحالات.
 *
 *   وأثقلُ من ذلك: الاسمُ يُقارَن خاماً في الشاشتَين. والزبونُ يكتب اسمه في
 *   واتساب كما يشاء — «أحمد» و«احمد» و«اَحمد» ثلاثةُ نصوصٍ بايتاً وشخصٌ
 *   واحد — والموظّفُ يبحث بالإملاء الذي في رأسه. وتسويةُ الاسم موجودةٌ في
 *   هذا المستودع منذ زمن، وتُستعمل **لاقتراح المكرّرين وحده**: الشيفرةُ
 *   الصحيحةُ مكتوبةٌ وموصولةٌ إلى المكان الخطأ.
 */

/* عمودُ drizzle أو مقتطفُ `sql` — كلاهما يُلصَق في القالب، والنوعُ الضيّق
   كان يقبل الثاني ويرفض الأوّل فيُكتب العمودُ نصّاً في مواضع الاستدعاء. */
type Frag = SQLWrapper;
export type { Frag };

/** المحارفُ التي تُسوّى قبل المقارنة — همزاتٌ وتاءٌ مربوطةٌ وحركاتٌ وتطويل. */
export const AR_FROM = 'أإآٱىةًٌٍَُِّْـ';
export const AR_TO = 'اااايه';

/**
 * تسويةُ الاسم في TS — وهي **النسخةُ المفحوصة**، و`NAME_KEY` أدناه تطابقها.
 * ونسختان لقاعدةٍ واحدة تتباعدان، فالحارسُ يُقارنهما على نصوصٍ حقيقيّة.
 */
export function nameKey(raw: string | null | undefined): string {
  if (!raw) return '';
  let out = '';
  for (const ch of raw) {
    const at = AR_FROM.indexOf(ch);
    if (at < 0) out += ch;
    else if (at < AR_TO.length) out += AR_TO[at];
  }
  return out.replace(/\s+/g, ' ').trim().toLowerCase();
}

/** ذيلُ الرقم: تسعُ خاناتٍ تُسقط رمزَ الدولة والصفرَ الوطنيّ فيتطابق 07 مع 9627. */
export function phoneTail(raw: string | null | undefined): string {
  const digits = (raw ?? '').replace(/[^0-9]/g, '');
  return digits.length >= 7 ? digits.slice(-9) : '';
}

/**
 * ★ `%` و`_` محرفا بدلٍ في `ilike`: بحثٌ عن «50%» بلا تهريبٍ **يطابق كلَّ
 * شيء**، و«a_b» يطابق ما ليس منه. والتهريبُ بالشرطة المائلة الخلفيّة — وهي
 * محرفُ الهروب الافتراضيّ في بوستجرس بلا `ESCAPE`.
 */
export function likePattern(q: string): string {
  return `%${q.trim().replace(/[\\%_]/g, (m) => `\\${m}`)}%`;
}

/** نفسُ تسوية `nameKey` بلغة القاعدة — والتطابقُ مقصودٌ ومفحوص. */
export const NAME_KEY = (col: Frag): Frag =>
  /* ★ `[[:space:]]` لا `\s`: قالبُ JS يأكل الشرطةَ المائلة فيصل إلى القاعدة
     `'s+'` — تعبيرٌ يستبدل **حرف s** بمسافة ولا يطوي مسافةً واحدة. عطلٌ
     صامتٌ تماماً: الاستعلام ينجح، والترشيحُ يخطئ على كلّ اسمٍ لاتينيّ. */
  sql`lower(btrim(regexp_replace(translate(coalesce(${col}, ''), ${AR_FROM}, ${AR_TO}), '[[:space:]]+', ' ', 'g')))`;

/** ذيلُ الرقم بلغة القاعدة — `null` لما هو أقصرُ من أن يكون رقماً. */
export const TAIL = (col: Frag): Frag =>
  sql`nullif(right(regexp_replace(coalesce(${col}, ''), '[^0-9]', '', 'g'), 9), '')`;

/**
 * مطابقةُ اسمٍ مسوّاةٌ من **الطرفين**.
 * وتسويةُ طرفٍ واحدٍ أسوأ من لا تسوية: يجد «احمد» من كتب «أحمد» ولا العكس،
 * فيتعلّم الموظّف أنّ البحث «أحياناً يشتغل» ويكفّ عن الوثوق به.
 */
export const nameMatch = (col: Frag, q: string): Frag =>
  sql`${NAME_KEY(col)} like ${likePattern(nameKey(q))}`;
