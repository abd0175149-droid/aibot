/**
 * ★ **معجمُ المنتج — مصطلحٌ واحدٌ لكلّ معنى.**
 *
 *   العطل الذي يمنعه، مقيسٌ على شاشاتٍ حيّة: صاحبُ مطعمٍ يقرأ «وحدة قراءة» في
 *   شاشة البوت، و«توكن» في الساحة، و«توكناتُ الذكاء» في الاستهلاك، و«توكن» في
 *   المعالج — أربعةُ أسماءٍ لرقمٍ واحد. فيظنّها أربعة حسابات، ويتّصل بالدعم
 *   يسأل أيَّها يُفوتَر عليه. ووضعُ المعرفة كان له **أربعُ** خرائطِ أسماءٍ
 *   مستقلّة (شاشة البوت، الساحة، لوحة المالك، ونصٌّ مكتوبٌ بيدٍ في الساحة)،
 *   واسمان للمفهوم نفسِه: «وضع القراءة» و«وضعُ المعرفة».
 *
 *   وأسوأُ صورةِ هذا العطل مكالمةُ دعم: العميل يقول «يقرأ نصّي كاملاً»
 *   والموظّف أمامه «حقنٌ كامل» — فيُشخّص حالةً غيرَ التي يصفها له.
 *
 * ⚠️ والمصطلحُ يُستورَد ولا يُكتب حرفيّاً في شاشة. حارسٌ في
 *    `apps/web/test/design-system.test.ts` يمنع نسخَه.
 */

/** الوحدة المعروضة للمالك. وهي نفسُها التي يحسبها الخادم — تغيّر الاسمُ لا الرقم. */
export const READ_UNIT = 'وحدة قراءة';
/** صيغةُ المعدود في نصٍّ جارٍ: «١٢٠ وحدةَ قراءةٍ من معرفتك». */
export const READ_UNIT_ACC = 'وحدةَ قراءةٍ';
/** الجمع: «ووحداتُ القراءة تُحاسَب». */
export const READ_UNIT_PL = 'وحدات القراءة';

/** اسمُ المفهوم — وكان له اسمان في شاشتين. */
export const KB_MODE_TERM = 'وضع القراءة';

export type KbMode = 'full' | 'hybrid' | 'rag';

/**
 * الأوضاع الثلاثة بلغةٍ تقول **ما يحدث** لا ما اسمه.
 * (‏`decideKnowledgeMode` في `packages/core/src/knowledge.ts` هو من يقرّرها.)
 */
export const KB_MODE: Record<KbMode, { label: string; how: string }> = {
  full: {
    label: 'يقرأ نصَّك كاملاً',
    how: 'دون العتبة الأولى، يُرسَل نصُّ معرفتك كاملاً مع كلّ سؤالٍ يصل.',
  },
  hybrid: {
    label: 'أساسيّات + استرجاع',
    how: 'فوق العتبة الأولى، لا يُرسَل إليه إلّا الأساسيّات وما يرتبط بالسؤال — أوفرُ وأدقّ.',
  },
  rag: {
    label: 'استرجاعٌ كامل',
    how: 'فوق العتبة الثانية، لا يُرسَل إلّا ما يرتبط بالسؤال — فمعرفةٌ بعشرة أضعافٍ لا تكلّفك عشرة أضعاف.',
  },
};

export const isKbMode = (v: string): v is KbMode =>
  v === 'full' || v === 'hybrid' || v === 'rag';

/**
 * ⚠️ لوحةُ المالك تقرأ `knowledge_mode` من الصفّ نصّاً (`string`)، فلا تُفهرَس
 *    به خريطةٌ مفاتيحُها ثلاثةٌ معروفة. والقيمةُ المجهولة تُعرض كما هي بدل أن
 *    تُعرض فارغةً — قيمةٌ جديدةٌ من ترحيلٍ لاحقٍ لا تُخفي الصفَّ كلَّه.
 */
export const kbModeLabel = (v: string | null | undefined): string =>
  (v && isKbMode(v) ? KB_MODE[v].label : (v ?? '—'));

/** العتبتان مكتوبتان في `decideKnowledgeMode` — ومعروضتان هنا بعينهما. */
export const MODE_THRESHOLD = 8_000;
export const RAG_THRESHOLD = 40_000;
/** الحدّ الموصى به لطول الشخصيّة: تُقرأ مع كلّ سؤال. */
export const PERSONA_LIMIT = 800;

export const decideKbMode = (units: number): KbMode =>
  (units < MODE_THRESHOLD ? 'full' : units <= RAG_THRESHOLD ? 'hybrid' : 'rag');

/**
 * ★ الزمنُ بالثانية في كلّ موضع.
 *
 *   الساحةُ كانت تطبع «٤٢٠ مِلّي» في صفّ الأداة و«٠.٤ ث» في لوحة الكلفة ثلاثَ
 *   كتلٍ تحتها — نفسُ القياس يُقرأ قياسَين، و«مِلّي» نصفُ ترجمةٍ لا تعني شيئاً
 *   لصاحب متجر.
 */
export const secs = (ms: number): string =>
  (ms < 100 ? 'أقلّ من 0.1' : (ms / 1000).toFixed(1));
