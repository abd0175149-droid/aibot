import { NextResponse } from 'next/server';

/**
 * ★ **نسخةُ الواجهة — لتُفحص في بوّابة النشر.**
 *
 *   العطل الذي وُلدت منه، وقد وقع فعلاً ثلاثَ نشراتٍ متتالية: بناءُ الواجهة
 *   فشل، فتراجع `deploy.sh` وأبقى **صورةَ واجهةٍ قديمة**، بينما نجح بناءُ
 *   الـAPI والعامل. وبوّابةُ الصحّة تفحص نسخةَ الـAPI وحدها، وتفحص الواجهةَ
 *   بأنّها «تردّ 200» — وهي تردّ 200 وهي متأخّرةٌ بثلاث نشرات.
 *
 *   فالنتيجةُ أسوأ من فشلٍ معلَن: خادمٌ بنصف نسخةٍ جديدة، وشاشاتٌ تنادي
 *   مساراتٍ تغيّر عقدُها. ولا شيء في المخرجات يقول ذلك — إلّا سطرُ تراجعٍ
 *   بين مئات أسطر البناء.
 *
 * ⚠️ والمسارُ `/rev` لا `/api/rev`: كلّ ما تحت `/api` مُعادُ توجيهه إلى
 *    الـAPI في `next.config.mjs`، فلن يصل هذا المعالجَ أبداً.
 */
export const dynamic = 'force-dynamic';

export function GET() {
  return NextResponse.json(
    { service: 'aibot-web', rev: process.env.GIT_REV ?? 'unknown' },
    { headers: { 'cache-control': 'no-store' } },
  );
}
