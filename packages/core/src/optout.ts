import { normalizeArabic } from './knowledge.js';

/**
 * ★★★ **عدولُ الزبون عن المراسلة — كان يُعامَل سؤالاً يُجاب عنه بودّ.**
 *
 *   زبونٌ يكتب «توقف» أو «لا تراسلوني» أو «stop» كان يحصل على ردٍّ لطيفٍ من
 *   النموذج، ثمّ رسالةٍ أخرى، ثمّ أخرى. والمخطَّطُ يحمل `opted_out_at`
 *   و`blocked_at` وجدولَ `optouts` منذ اليوم الأوّل، وصفحةُ الخصوصيّة تَعِد
 *   باحترام العدول — ولا سطرَ في خطّ الأنابيب يقرأ أيّاً منها. وعدٌ مكتوبٌ
 *   بلا كاشفٍ ولا بوّابة.
 *
 *   وهذا ليس ذوقاً: سياسةُ واتساب للأعمال تشترط احترامَ طلب الإيقاف، وقانونُ
 *   حماية البيانات الأردنيّ (٢٤/٢٠٢٣) الذي تستشهد به صفحةُ الخصوصيّة يجعل
 *   الاعتراضَ على المعالجة حقّاً صريحاً.
 *
 * ⚠️ **الكشفُ ضيّقٌ عمداً.** عبارةٌ كاملةٌ في أوّل الرسالة أو رسالةٌ كلُّها
 *    العبارة — لا «كلمةٌ في أيّ موضع». «توقف عن إرسال العروض» عدول؛ أمّا
 *    «متى تتوقف الحجوزات؟» فسؤال. والخطأُ في الاتّجاهين مكلف: عدولٌ فائتٌ
 *    مخالفةٌ، وعدولٌ كاذبٌ يُسكت البوتَ عن زبونٍ يسأل. فعند الشكّ لا يُكتشف،
 *    والموظّفُ يملك زرّاً صريحاً في بطاقة الجهة.
 *
 * ⚠️ ولا `\b`: حدُّ الكلمة في JavaScript لا يتحقّق بين حرفٍ عربيٍّ ومسافة
 *    (نفسُ الفخّ الموثَّق في `knowledge.ts`). فالحدُّ مسافةٌ صريحةٌ أو نهاية.
 */

/* كلُّ ما يلي يُطابَق **بعد** `normalizeArabic` — فلا همزةَ ولا تاءَ مربوطة هنا. */

/**
 * ★★ **فعلٌ مجرَّدٌ ليس عدولاً إلّا وحدَه أو مع اسمِ المراسلة.**
 *
 *   أوّلُ نسخةٍ عاملت «بطل» و«وقف» و`stop` بادئاتٍ — فكشف اختبارُها السالب أنّ
 *   «stop by tomorrow?» يُكشف عدولاً، ومثلُه «بطل الحجز» و«وقف الطلب» وهي
 *   طلباتٌ لا عدول. عدولٌ كاذبٌ يُسكت البوتَ عن زبونٍ يطلب شيئاً، ولا يراه أحدٌ
 *   حتّى يشكو. فالفعلُ المجرَّد يُقبل في حالتَين لا غير: رسالةٌ هو كلُّها (مع
 *   «لو سمحت» وأخواتها)، أو يليه خلال كلمتَين اسمٌ من أسماء المراسلة.
 */
const AR_VERBS = ['توقف', 'توقفوا', 'وقف', 'اوقف', 'اوقفوا', 'كفايه', 'كفى', 'بطل', 'بطلوا'];
const AR_NOUNS = [
  'رسائل', 'الرسائل', 'رسايل', 'الرسايل', 'مراسله', 'المراسله', 'اشعارات', 'الاشعارات',
  'عروض', 'العروض', 'اعلانات', 'الاعلانات', 'ازعاج', 'الازعاج',
];
const POLITE = '(لو سمحت|من فضلك|بليز|please|pls)';

/** عباراتٌ صريحةٌ متعدّدةُ الكلمات — تُقبل بادئةً: ما بعدها لا يبدّل معناها. */
const AR_PHRASES = [
  'لا تراسلني', 'لا تراسلوني', 'لا ترسل', 'لا ترسلوا', 'لا ترسلولي', 'لا ترسلوا لي',
  'ما بدي رسائل', 'ما بدي اشعارات', 'ما بدي عروض', 'مش عايز رسائل',
  'الغاء الاشتراك', 'الغي اشتراكي', 'احذفوني', 'احذفني', 'امسحوني', 'امسحني',
  'احذفوا رقمي', 'امسحوا رقمي', 'شيلوا رقمي', 'شيل رقمي',
];

const EN_BARE = ['stop', 'cancel', 'quit', 'end'];
const EN_PHRASES = [
  'unsubscribe', 'opt out', 'optout', 'stop all', 'stop messages', 'stop messaging',
  'stop texting', 'remove me', 'delete me', 'take me off',
];

const longestFirst = (xs: readonly string[]): string => [...xs].sort((a, b) => b.length - a.length).join('|');

/* ★ الحدُّ مسافةٌ صريحةٌ أو نهاية — لا `\b` (لا يعمل مع العربيّة). */
const AR_PHRASE_RE = new RegExp(`^(${longestFirst(AR_PHRASES)})(\\s|$)`);
const AR_BARE_RE = new RegExp(`^(${longestFirst(AR_VERBS)})(\\s${POLITE})?$`);
const AR_VERB_NOUN_RE = new RegExp(`^(${longestFirst(AR_VERBS)})(\\s\\S+){0,2}\\s(${AR_NOUNS.join('|')})(\\s|$)`);
const EN_PHRASE_RE = new RegExp(`^(${longestFirst(EN_PHRASES)})(\\s|$)`, 'i');
const EN_BARE_RE = new RegExp(`^(${longestFirst(EN_BARE)})(\\s(please|pls|now))?$`, 'i');

/**
 * هل هذه الرسالةُ طلبُ عدول؟
 *
 * ⚠️ رسالةٌ طويلةٌ (فوق ثماني كلمات) لا تُعدّ عدولاً ولو بدأت بالعبارة: زبونٌ
 *    يكتب «توقف عن ارسال الفاتورة القديمة وابعت الجديدة لو سمحت» يطلب شيئاً.
 *    والعدولُ الحقيقيُّ قصيرٌ في الغالب — وحين لا يكون كذلك فالموظّفُ يقرأ.
 */
export function detectOptOut(text: string | null | undefined): boolean {
  if (!text) return false;
  const q = normalizeArabic(text).toLowerCase();
  if (!q) return false;
  const words = q.split(' ').filter(Boolean);
  if (words.length > 8) return false;
  return AR_PHRASE_RE.test(q) || AR_BARE_RE.test(q) || AR_VERB_NOUN_RE.test(q)
    || EN_PHRASE_RE.test(q) || EN_BARE_RE.test(q);
}

/** نصُّ التأكيد الوحيد الذي يُرسَل بعد العدول — ثمّ لا شيء. */
export const OPTOUT_ACK_MSG = 'تمّ. لن نراسلك بعد الآن. لو غيّرت رأيك ابعت «اشترك».';

/** عباراتُ العودة — أضيقُ من العدول عمداً: العودةُ تُعلَن ولا تُخمَّن. */
const OPTIN = /^(اشترك|اشتراك|ابعتولي|ابعتوا لي|رجعوني|start|subscribe|resume)(\s|$)/i;

export function detectOptIn(text: string | null | undefined): boolean {
  if (!text) return false;
  const q = normalizeArabic(text).toLowerCase();
  return Boolean(q) && q.split(' ').filter(Boolean).length <= 3 && OPTIN.test(q);
}
