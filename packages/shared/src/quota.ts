/**
 * ★ قواعدُ سقف النوافذ — عتباتُه، وحسابُ عبورها، ونصُّ عاقبته.
 *
 * ولماذا في `shared` لا في العامل: **النصُّ يُقال في موضعين.** العاملُ يدفعه
 * إشعاراً إلى مالك المستأجر، والـAPI يُرجعه لشاشتَي الاستهلاك والرئيسيّة.
 * ونسختان من نصٍّ كهذا تتباعدان — وقد تباعدتا فعلاً: كانت الواجهة تقول
 * «فريقك يردّ يدويّاً بلا حدّ» والكودُ يمنع ردَّ الموظّف على محادثةٍ جديدة
 * كما يمنع ردَّ البوت. فصار للنصّ موضعٌ واحدٌ يقرأه الاثنان.
 */

/** العتباتُ الثلاث — مئويّةٌ صحيحة، ومرتّبةٌ تصاعديّاً (يعتمد عليه `crossedThresholds`). */
export const QUOTA_THRESHOLDS = [80, 95, 100] as const;

/**
 * ما يحدث **فعلاً** عند بلوغ السقف، مقروءاً من `checkQuota` في طبقة الإرسال:
 *
 *   allowed = used < limit || policy === 'allow_bill'
 *
 * وثلاث حقائقٍ تتبعه، وكلُّها في النصّ لأنّ كلَّها يفاجئ العميل:
 *  · `allow_bill` وحدها تستمرّ؛ و`block` و`handoff_only` **متطابقتان في الكود**
 *    — كلتاهما تمنع الإرسال. فلا نصّان مختلفان نَعِدُ في أحدهما بما لا يفعله.
 *  · والحارسُ لا يستثني مصدراً ولا دوراً ⟵ ردُّ **الموظّف** على محادثةٍ جديدة
 *    يُرفض هو أيضاً. وهذا ما كانت الواجهة تَعِد بعكسه.
 *  · والفحصُ مشروطٌ بـ`!win.billedAt` ⟵ المحادثاتُ المُفوترةُ هذا الشهر تُكمل،
 *    والمنعُ يقع على النوافذ الجديدة وحدها. والوارد يُحفظ دائماً (لا فحصَ سقفٍ
 *    في الوارد) ⟵ لا رسالةَ تُفقد.
 */
const CONSEQUENCE: Record<string, string> = {
  allow_bill: 'عند بلوغ السقف يستمرّ بوتك في الردّ، وكلّ نافذةٍ زائدة تُضاف إلى فاتورة الشهر.',
  block: 'عند بلوغ السقف يتوقّف الردّ على كلّ محادثةٍ جديدة — من بوتك ومن موظّفك معاً. '
    + 'والمحادثاتُ المُفوترةُ هذا الشهر تُكمل، والرسائل تصل وتُحفظ فلا يُفقد شيء.',
  handoff_only: 'عند بلوغ السقف يتوقّف الردّ على كلّ محادثةٍ جديدة — من بوتك ومن موظّفك معاً. '
    + 'والمحادثاتُ المُفوترةُ هذا الشهر تُكمل، والرسائل تصل وتُحفظ فلا يُفقد شيء.',
};

/** وبعد البلوغ تُصاغ بالماضي — «عند بلوغ السقف» تُقرأ تحذيراً لمن بلغه. */
const CONSEQUENCE_AT_CAP: Record<string, string> = {
  allow_bill: 'بوتك يستمرّ في الردّ، وكلّ نافذةٍ من الآن تُضاف إلى فاتورة الشهر.',
  block: 'الردُّ على المحادثات الجديدة متوقّف — من بوتك ومن موظّفك معاً. والمحادثاتُ '
    + 'المُفوترةُ هذا الشهر تُكمل، والرسائل تصل وتُحفظ فلا يُفقد شيء.',
  handoff_only: 'الردُّ على المحادثات الجديدة متوقّف — من بوتك ومن موظّفك معاً. والمحادثاتُ '
    + 'المُفوترةُ هذا الشهر تُكمل، والرسائل تصل وتُحفظ فلا يُفقد شيء.',
};

/** `atCap`: هل بُلغ السقف فعلاً (فتُصاغ العاقبة بالماضي) أم يُحذَّر منه. */
export function capConsequence(policy: string, atCap: boolean): string {
  const map = atCap ? CONSEQUENCE_AT_CAP : CONSEQUENCE;
  // المجهولُ يُعامَل معاملةَ المانع: وعدٌ بالاستمرار لا يجوز أن يأتي من مفتاحٍ غير معروف
  return map[policy] ?? map.handoff_only!;
}

/**
 * العتباتُ التي **عبرها** الانتقال من `before` إلى `after` نافذةً مُفوترة.
 *
 * العبورُ حافّة: `نسبة(before) < عتبة ≤ نسبة(after)`. فـ79 ⟶ 80 يعبر الثمانين،
 * و80 ⟶ 81 لا يعبر شيئاً — ولو كان الشرط «هو فوق الثمانين الآن» لأطلق إنذاراً
 * مع كلّ نافذةٍ بعدها، فأغرق الصندوق وأُطفئت الإشعارات: أي بلا إنذارٍ من جديد.
 *
 * وقفزةٌ واحدة قد تعبر أكثر من عتبةٍ حين يكون السقف صغيراً (سقف 4: النافذةُ
 * الرابعة تنقل من 75٪ إلى 100٪ فتعبر الثلاث).
 *
 * والحسابُ بالضرب التبادليّ لا بالقسمة: `used*100 >= t*limit` بلا كسورٍ عائمة،
 * فلا تُفلت عتبةٌ بفرقِ تقريبٍ في الرقم السابع (سقف 3: ثمانون بالمئة منه 2.4).
 */
export function crossedThresholds(before: number, after: number, limit: number): number[] {
  if (!Number.isFinite(limit) || limit <= 0) return []; // بلا سقفٍ لا عتبة
  if (!(after > before)) return [];
  const reached = (n: number, t: number) => n * 100 >= t * limit;
  return QUOTA_THRESHOLDS.filter((t) => !reached(before, t) && reached(after, t));
}
