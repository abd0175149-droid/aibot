-- ★★★ **الوراثةُ كانت تُبطل كلَّ `REVOKE` على دور التطبيق.**
--
-- كُشف في أوّل تشغيلٍ لـ`packages/db/test/rls-leak.sql` — وهو ملفٌّ مكتوبٌ منذ
-- دفعاتٍ بأحدَ عشرَ تأكيداً لم يُشغّله شيءٌ قطّ. سقط التأكيدُ السابع فوراً:
--
--     ERROR:  ✘ خطر: سجلّ التدقيق قابلٌ للتعديل
--
-- والآليّةُ قِيست على قاعدة الإنتاج نفسِها:
--   · `0002` و`0003` يمنحان `aibot_app` على `audit_log`: SELECT + INSERT،
--     ثمّ `REVOKE UPDATE, DELETE` — والمنحُ المباشرُ فعلاً هو SELECT+INSERT.
--   · لكنّ `0003` يمنح `aibot_platform` صلاحيّاتٍ على **كلّ** الجداول، ويمنح
--     عضويّتَه لـ`aibot_app`. والأدوارُ تُنشأ بالافتراض `INHERIT`.
--   · فالنتيجة: `has_table_privilege('aibot_app','audit_log','UPDATE') = t`
--     رغم `REVOKE` صريحَين. سجلُّ التدقيق يُزوَّر، والقيدُ زينةٌ مكتوبة.
--
-- وهذا يخالف التصميمَ الموصوفَ في `0003` نفسِه بالنصّ: «`aibot_platform`
-- يبقى للوصول العابر، **ويُنتقل إليه بـ`SET LOCAL ROLE` داخل المعاملة
-- وحدها**». والوراثةُ تجعله متاحاً **دائماً** بلا انتقال.
--
-- ① `NOINHERIT` يُعيد التصميمَ إلى ما وُصف: صلاحيّاتُ المنصّة لا تُكتسب إلّا
--    بانتقالٍ صريح. و`SET LOCAL ROLE` يبقى عاملاً — العضويّةُ تكفي له،
--    والوراثةُ شرطُ الاكتسابِ **التلقائيّ** لا شرطُ الانتقال.
--
-- ⚠️ وقِيس قبل التغيير أنّ هذا آمن: كلُّ جداول المخطَّط لها منحٌ **مباشرٌ**
--    لـ`aibot_app` (‏`0002`)، والوحيدُ بلا منحٍ مباشر هو `schema_migrations`
--    — وهو لا يُمسّ إلّا من `deploy.sh` بدور مالك القاعدة لا بدور التطبيق.
--    و`withPlatform` ينتقل بـ`SET LOCAL ROLE aibot_platform` (‏`tenant.ts`).
--
-- ② وسجلُّ التدقيق إضافةٌ فقط **للجميع** لا لدور التطبيق وحده: لا سطرَ في
--    الشيفرة كلِّها يعدّله أو يحذفه (‏`auditLog` تُقرأ وتُدرَج لا غير)، فالمنعُ
--    لا يكلّف شيئاً ويُغلق الباب من الجهتين.
--
-- ⚠️ ومتماثِل: النشر يُطبّق كلّ الترحيلات في كلّ مرّة.
-- ════════════════════════════════════════════════════════════════

-- ① صلاحيّاتُ المنصّة بانتقالٍ صريحٍ لا بالوراثة
ALTER ROLE aibot_app NOINHERIT;

-- ② وسجلُّ التدقيق لا يُعدَّل ولا يُحذف — من أيّ دورٍ كان
REVOKE UPDATE, DELETE ON audit_log FROM aibot_app;
REVOKE UPDATE, DELETE ON audit_log FROM aibot_platform;
