-- نافذةٌ مفتوحةٌ **واحدة** لكلّ محادثة — القيدُ الذي كان الكود يفترضه ولا وجود له.
--
-- 🔴 العطل: `openOrExtendWindow` في `apps/worker/src/inbound.ts` تقرأ «هل من نافذةٍ
--    مفتوحة؟» ثمّ تكتب، وبين القراءة والكتابة لا قفل. وتعليقُها ينصّ حرفيّاً على
--    أنّ «القيد الفريد الجزئيّ في القاعدة (closed_at IS NULL) هو ما يضمن ذلك عند
--    تدفّقٍ متزامن، لا هذا الكود» — ولم يكن ذلك القيد في أيّ ترحيل. أي أنّ الضمان
--    كان **مُحالاً إلى جهةٍ غير موجودة**.
--
--    وأثرُه فوترةٌ مزدوجة، لا مجرّد صفٍّ زائد: النافذة هي وحدةُ الفوترة، فمحادثةٌ
--    بنافذتَين مفتوحتَين تُختَم مرّتين في نفس الـ٢٤ ساعة ⟶ يُحاسَب العميل مرّتين
--    على محادثةٍ واحدة، ويُستهلك سقفُ باقته ضعفَ ما استحقّ.
--
--    الشرطُ الذي يُظهره: محادثةٌ نافذتُها **مغلقة** (وهي الحالة التي تصنعها صيانة
--    `closeExpiredWindows` كلَّ عشر دقائق) ثمّ رسالتان أو أكثر تصلان متزامنتَين —
--    زبونٌ يكتب ثلاثة أسطر بسرعة، أو دفعةٌ من ميتا. وكشفه اختبارُ التحمّل:
--    `apps/worker/scripts/load-test.ts` (حُقنة BURST) طبع على الخادم:
--      «3 رسالةً متزامنةً على محادثةٍ واحدة نافذتُها مغلقة … منها مفتوحة: 3»
--
-- ولماذا الفهرسُ وحده يكفي بلا تعديل شيفرة: الإدراج هناك `ON CONFLICT DO NOTHING`
-- **بلا هدفٍ محدَّد**، وهذا الشكل يبتلع أيَّ انتهاكِ تفرّد — فتخسر المتسابقةُ
-- الثانية بصمتٍ وتبقى نافذةٌ واحدة، وهو بالضبط ما يقوله التعليق. فيصحّ الكود
-- المنشور بمجرّد وجود الفهرس، بلا نشرةٍ ولا توقّف.
--
-- وثمنٌ معروفٌ يُذكر لا يُخفى: الخاسرة لا تزيد `messages_in`، فالعدُّ أقلُّ بواحدٍ
-- في سباقٍ نادر. والإصلاح الأنظف (إعادةُ القراءة ثمّ التمديد) يحتاج نشراً —
-- وحمايةُ الفاتورة الآن أولى من انتظاره.
CREATE UNIQUE INDEX IF NOT EXISTS "windows_one_open_uq"
  ON "conversation_windows" ("conversation_id") WHERE "closed_at" IS NULL;
