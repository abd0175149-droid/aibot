-- ★ تبويبان يُجدّدان الجلسة معاً كانا يُسقطان المستخدم من الحساب.
--
-- `rotateSession` قراءةٌ ثمّ كتابة: التبويبُ الأوّل يقرأ الصفَّ ويُدوّر
-- التوكن، والثاني يصل بتوكنٍ صار سابقاً فلا يجد صفّاً — فيُردّ ٤٠١ **ومعه
-- مسحُ الكوكي**. والكوكي مشتركٌ بين التبويبات كلِّها، فيسقط التبويب الأوّل
-- الذي كان يعمل بنجاحٍ قبل ثانية. والمستخدم لم يفعل شيئاً إلّا أنّه فتح
-- شاشتين — وهو ما يفعله الموظّف كلَّ يوم (إنبوكسٌ وجهةُ اتّصال).
--
-- والعلاجُ شقّان:
--  ① التدويرُ عبارةٌ **واحدة** (‏`UPDATE … WHERE refresh_hash = …`)‏: القراءةُ
--    المنفصلة تسمح لمتسابقَين أن يمرّا معاً فيُصدر كلٌّ منهما توكناً ويُخزَّن
--    آخرُهما وحده — فيحمل الكوكي توكناً لا يطابق شيئاً. والعبارةُ الواحدة
--    تُقفل الصفَّ فيفوز واحدٌ بيقين.
--  ② والخاسرُ لا يُطرَد: التجزئةُ السابقة تبقى مقبولةً نصفَ دقيقة، فيأخذ
--    توكنَ وصولٍ جديداً ولا يلمس الكوكي.
--
-- ⚠️ ولا فهرسَ كان على `refresh_hash` — وهو عمودُ البحث في كلّ تجديد. ومع
--    شرطٍ ثانٍ على `prev_refresh_hash` يصير المسحُ الكاملُ مسحَين.
-- ⚠️ ومتماثِل: النشر يُطبّق كلّ الترحيلات في كلّ مرّة.
-- ════════════════════════════════════════════════════════════════

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS prev_refresh_hash text;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS rotated_at timestamptz;

CREATE INDEX IF NOT EXISTS sessions_refresh_hash_idx ON sessions (refresh_hash);
CREATE INDEX IF NOT EXISTS sessions_prev_refresh_hash_idx ON sessions (prev_refresh_hash)
  WHERE prev_refresh_hash IS NOT NULL;
