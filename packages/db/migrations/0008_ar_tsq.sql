-- ════════════════════════════════════════════════════════════════
-- ★ `plainto_tsquery` يعطف الكلمات بـAND — فسؤالٌ طبيعيٌّ لا يُطابق شيئاً.
--
-- مقيسٌ على الخادم الحيّ (2026-09-24). المستند:
--   «سعر الغرفة المفردة ٤٥ ديناراً والمزدوجة ٦٥ ديناراً»
-- والسؤال:
--   «كم سعر الغرفة؟»
-- يُنتج `plainto_tsquery` الاستعلامَ `'كم' & 'سعر' & 'غرفه'`، و«كم» ليست في
-- المستند — **فالمطابقة `false`**. أي أنّ الفرع المعجميّ في الاسترجاع الهجين
-- يسكت على أغلب أسئلة الزبائن الحقيقيّة: كلمةُ استفهامٍ واحدةٌ زائدة تُبطل
-- الشرطَ كلَّه. وكلمات الاستفهام والحشو هي بعينها ما يبدأ به الزبون كلامه.
--
-- ولا يظهر العطل خطأً: الفرع يعود بصفر صفوف، فيبقى المتّجهُ وحده، ويُقرأ
-- الأمرُ «الاسترجاع الدلاليّ لم يجد» لا «نصفُ الاسترجاع معطَّل». وذلك أسوأ
-- من الفشل الصريح: الهجينُ **يقول** إنّه فرعان.
--
-- ★ والعطف بـOR هو الصحيح لا حلّاً وسطاً: `ts_rank` يُرتّب بعدد الكلمات
-- المُطابقة وقربها، فالمستندُ الذي يُطابق كلمتين يسبق الذي يُطابق واحدة.
-- والدقّةُ تأتي من الترتيب لا من إقصاء كلّ ما لم يُطابق كلَّ الكلمات.
--
-- ⚠️ ولا اجتذارَ ثانٍ: `to_tsquery('arabic', 'غرفه')` تجذّر «غرفه» مرّةً
--    أخرى فتصير «غرف» ولا تُطابق «غرفه» في المستند. لذلك تُركَّب اللفائظ
--    نصّاً مُقتبَساً ويُحوَّل إلى `tsquery` بالتحويل المباشر — بلا قاموس.
--    (قيسَ هذا أيضاً: مع الاجتذار المزدوج يسقط الترتيب من 0.0405 إلى 0.0203
--    لأنّ «غرفه» لا تُطابق.)
-- ⚠️ وسؤالٌ كلُّه ترقيمٌ يُنتج `NULL` — و`tsv @@ NULL` ليست `true` فيُتجاهل
--    الفرع بلا خطأ. ولذلك `COALESCE` على `ts_rank` في الاستعلام: بلاها
--    يصير المجموع `NULL` وتتقدّم صفوفُه في `ORDER BY … DESC`.
-- ⚠️ ومتماثِل: النشر يُطبّق كلّ الترحيلات في كلّ مرّة.
-- ════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION ar_tsq(q text) RETURNS tsquery
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT NULLIF(
    array_to_string(
      ARRAY(
        SELECT quote_literal(lex)
          FROM unnest(tsvector_to_array(to_tsvector('arabic', ar_norm(coalesce(q, ''))))) AS lex
      ),
      ' | '
    ),
    ''
  )::tsquery
$$;
