#!/bin/bash
# ════════════════════════════════════════════════════════════════
# AiBot — تشغيل اختبار التسرّب بين المستأجرين على قاعدةٍ **حقيقيّة**.
#
# ★ لماذا وُجد: `packages/db/test/rls-leak.sql` مكتوبٌ منذ دفعاتٍ ويحمل
#   أحدَ عشرَ تأكيداً على أنّ **بوستجرس نفسه** يمنع التسرّب — ولم يكن في
#   المستودع كلِّه سطرٌ واحدٌ يُشغّله. لا سكربت، ولا خطوةٌ في النشر، ولا
#   وظيفةٌ في CI. الإشارةُ الوحيدة إليه صفٌّ في جدولِ وثيقة.
#
#   واختبارٌ لا يُشغَّل ليس اختباراً: هو ادّعاءٌ مكتوبٌ يُقرأ فيُطمئن. ووثيقةُ
#   الحالة تعدّه «٩ تأكيدات» في عمود المُنجَز — فصار غيابُه مخفيّاً خلف
#   حضوره في جدول.
#
# ★ وما يُثبته ولا يستطيعه vitest: أنّ السياساتِ مكتوبةٌ في القاعدة وسارية،
#   وأنّ دورَ التطبيق **ليس** سوبريوزر (والسوبريوزر يتجاوز RLS حتّى مع
#   FORCE). كلُّ اختبارات العزل الأخرى في المستودع تعبيراتٌ نمطيّةٌ على نصّ
#   الشيفرة: تمسك «نسيتُ `where`» ولا تمسك «السياسةُ لم تُطبَّق أصلاً».
#
# 🔴 **لا يُشغَّل على الإنتاج.** السكربت يُدخل مستأجرَين ثمّ يحذفهما، ويُجري
#    `DELETE ... CASCADE`. فهو يرفض العمل على قاعدةٍ فيها مستأجرون —
#    والرفضُ قبل أوّل عبارةٍ لا بعدها.
#
# الاستعمال (على قاعدةٍ مؤقّتة):
#   PGHOST=127.0.0.1 PGPORT=5432 PGUSER=postgres PGPASSWORD=… PGDATABASE=aibot \
#     ops/rls-leak.sh
# ════════════════════════════════════════════════════════════════
set -Eeuo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MIGRATIONS="${ROOT}/packages/db/migrations"
LEAK="${ROOT}/packages/db/test/rls-leak.sql"

: "${PGHOST:?PGHOST غير مضبوط — عيّن قاعدةً مؤقّتة}"
: "${PGUSER:?PGUSER غير مضبوط}"
: "${PGDATABASE:?PGDATABASE غير مضبوط}"
export PGPORT="${PGPORT:-5432}"

say() { printf '\n▶ %s\n' "$1"; }
fail() { printf '  ✘ %s\n' "$1" >&2; }

psqlq() { psql -v ON_ERROR_STOP=1 -qAt -c "$1"; }

# ── 0. حارسُ الإنتاج — قبل أيّ عبارةٍ تكتب ──────────────────────
# 🔴 هذا هو الفرقُ بين أداةِ تحقّقٍ وأداةِ تدمير. السكربت يحذف مستأجرَين
#    بـCASCADE، فقاعدةٌ فيها عملاءُ حقيقيّون ليست موضعَه إطلاقاً.
#    والفحصُ على **وجود** الجدول أوّلاً: قاعدةٌ فارغةٌ تماماً لم تُرحَّل بعد.
say "حارس الإنتاج"
HAS_TENANTS="$(psqlq "SELECT to_regclass('public.tenants') IS NOT NULL;")"
if [ "$HAS_TENANTS" = "t" ]; then
  N="$(psqlq "SELECT count(*) FROM tenants WHERE slug NOT IN ('alpha','beta');")"
  if [ "${N:-0}" -ne 0 ]; then
    fail "القاعدة ${PGDATABASE}@${PGHOST} فيها ${N} مستأجراً حقيقيّاً."
    fail "هذا السكربت يُدخل ويحذف بـCASCADE — لا يُشغَّل إلّا على قاعدةٍ مؤقّتة."
    exit 1
  fi
fi
echo "  ✔ لا مستأجرَ حقيقيٌّ في ${PGDATABASE}@${PGHOST}"

# ── 1. الترحيلات — بنفس ترتيب النشر وبنفس الذرّيّة ──────────────
# ⚠️ وبنفس الترتيب الأبجديّ الذي يستعمله `deploy.sh`: اختبارٌ يُرحّل بترتيبٍ
#    آخر يشهد على مخطّطٍ غيرِ الذي يعمل.
say "الترحيل"
for f in "${MIGRATIONS}"/*.sql; do
  printf '  → %s\n' "$(basename "$f")"
  psql -v ON_ERROR_STOP=1 --single-transaction -q -f "$f" > /dev/null
done
echo "  ✔ المخطّط جاهز"

# ── 2. كلمةُ دور التطبيق — الاختبار يتّصل بها لا بمالك القاعدة ──
# ⚠️ ولا سرَّ في السكربت: تُقرأ من البيئة، وقيمتُها هنا لقاعدةٍ مؤقّتةٍ تُرمى.
say "دور التطبيق"
APP_PW="${APP_DB_PASSWORD:-rls_leak_probe}"
psqlq "ALTER ROLE aibot_app LOGIN PASSWORD '${APP_PW}';" > /dev/null
IS_SUPER="$(psqlq "SELECT rolsuper FROM pg_roles WHERE rolname='aibot_app';")"
if [ "$IS_SUPER" != "f" ]; then
  fail "aibot_app سوبريوزر — والسوبريوزر يتجاوز RLS حتّى مع FORCE."
  fail "فكلُّ ما يلي سيمرّ بلا أن يُثبت شيئاً."
  exit 1
fi
echo "  ✔ aibot_app دورٌ عاديّ — السياسات تسري عليه"

# ── 3. الاختبار نفسه ───────────────────────────────────────────
say "اختبار التسرّب"
psql -v ON_ERROR_STOP=1 -f "$LEAK"

printf '\n✅ العزل مُثبَتٌ على قاعدةٍ حقيقيّة — لا على نصّ الشيفرة\n'
