# ── 8ب. القرص — وهو ما يُسقط كلَّ شيءٍ دفعةً واحدة ───────────────
# 🔴 قرصٌ يمتلئ لا يُسقط خدمةً واحدة: تتوقّف القاعدةُ عن الكتابة، ويعجز دوكر
