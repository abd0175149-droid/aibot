# ⚠️ والتقليمُ مشروطٌ ومحدودٌ بالعمر: هذا خادمٌ مشترك، وذاكرةُ البناء مشتركةٌ
#    بين المشاريع. فلا يُقلَّم شيءٌ ما لم يضِق القرص فعلاً، ولا يُقلَّم إلّا ما
