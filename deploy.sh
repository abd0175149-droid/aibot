  #   الأسبوعين» في كلّ نشرةٍ ليومٍ كامل (نشراتٌ متعدّدةٌ في اليوم تُبقي الذاكرةَ
  #   كلَّها أحدثَ من أسبوعين). وتقليمُ ٧٢ ساعةً يدويّاً حرّر ٦٨ غيغا (٢٦ أيلول).
  if [ "${DISK_PCT:-0}" -ge 80 ]; then
