#!/bin/bash
# ════════════════════════════════════════════════════════════════
# AiBot — نصّ النشر
#
# العقد: نسخةٌ احتياطيّة قبل أيّ لمس · صورٌ موسومةٌ للتراجع · الترحيل يُظهر
# خطأه · **بوّابة صحّةٍ تُقرّر النجاح** · وتراجعٌ تلقائيّ عند الفشل.
#
# 🔴 الفخّ الذي أُعيدت كتابة البوّابة من أجله (مُتحقَّقٌ منه على الخادم 2026-09-21):
#    https://aibot.masaros.net/api/health يردّ **200 الآن** — من تطبيق MasarOS
#    عبر wildcard على *.masaros.net. فبوّابةٌ تنتظر «200» تنجح فوراً بينما
#    AiBot غير موصولٍ إطلاقاً، ويُعلن النشر نجاحه عن نظامٍ لا يعمل.
#    لذلك ثلاثة شروطٍ معاً لا واحد:
#      ① الفحص على 127.0.0.1 لا على النطاق العامّ.
#      ② مطابقة **جسم** الاستجابة: "service":"aibot".
#      ③ مطابقة GIT_REV — فلا تمرّ البوّابة على نسخةٍ قديمة ما زالت تعمل.
# ════════════════════════════════════════════════════════════════
# 🔴 إن رأيت: «set: pipefail: invalid option name» — فالملفّ بنهايات CRLF.
#    ليس عطلاً في bash: `` يلتصق بـ`pipefail` فيصير خياراً مجهولاً، والرسالة
#    تُضلّل تماماً. سببه نسخةٌ من ويندوز سبقت `.gitattributes`. الإصلاح:
#      rm deploy.sh && git checkout -- deploy.sh && chmod +x deploy.sh
#    (ضاع بسببه شهرٌ من النشر اليدويّ: السكربت لم يعمل قطّ فلم يُستعمل.)
set -Eeuo pipefail

API_PORT="${API_PORT:-4100}"
WEB_PORT="${WEB_PORT:-3070}"
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="${HOME}/backups/aibot"
SERVICES="api worker web"
PUBLIC_URL="${PUBLIC_URL:-https://aibot.masaros.net}"

say()  { echo -e "\n▶ $1"; }
fail() { echo -e "\n❌ $1" >&2; }

rollback() {
  # 🔴 نزعُ المصيدتَين **أوّلَ شيء**. بعد تسليح EXIT صارتا اثنتين: فشلٌ حقيقيّ
  #    يُطلق ERR فتُنادى هذه، ثمّ تخرج بـ1 فتُطلق EXIT فتُنادى ثانيةً — ويصطدم
  #    `docker compose up` بنفسه («container name is already in use»، وهو
  #    العطلُ الموصوفُ أسفله). والنزعُ يحمي كذلك من فشل `docker tag` هنا.
  trap - ERR EXIT
  fail "فشل النشر — تراجع إلى وسوم rollback-${STAMP}"
  for s in $SERVICES; do
    if docker image inspect "aibot-${s}:rollback-${STAMP}" >/dev/null 2>&1; then
      docker tag "aibot-${s}:rollback-${STAMP}" "aibot-${s}:latest"
    fi
  done
  # 🔴 لا --force-recreate: آليّته تُعيد تسمية الحاوية إلى <id>_<name> كخطوةٍ
  #    وسيطة، فيتولّد الاسم نفسه في كلّ محاولةٍ ويصطدم ببقايا السابقة:
  #    «Conflict. The container name is already in use». أفشل ثلاث نشرات،
  #    وأفشل التراجعَ نفسه مرّةً فكادت الخدمة تبقى ساقطة.
  #    الحذف الصريح ثمّ الإنشاء لا يمرّ باسمٍ وسيط إطلاقاً.
  # ★★ سجلُّ ما فشل يُحفظ **قبل** حذف الحاويات — و`rm -sf` يمحوه معها.
  #    وبلا ذلك يقول النشرُ «فشل» ولا يقول لماذا: شكوتُ من هذا بنفسي حين
  #    سقطت بوّابةُ العامل ولم أجد سطراً واحداً يشرح السبب.
  for s in $SERVICES; do
    docker compose logs --no-color --tail 200 "$s" > "${BACKUP_DIR}/fail-${STAMP}-${s}.log" 2>&1 || true
  done
  echo "سجلّاتُ الفشل: ${BACKUP_DIR}/fail-${STAMP}-*.log"
  docker compose rm -sf $SERVICES 2>/dev/null || true
  docker compose up -d --no-build $SERVICES || true
  echo "النسخة الاحتياطيّة: ${BACKUP_DIR}/db-${STAMP}.sql.gz"
  exit 1
}
trap rollback ERR

# 🔴 **`exit 1` لا يُطلق `trap … ERR`** — دلالةُ bash لا علّةُ سكربت (مُجرَّبةٌ
#    على bash 5: `false` تُطلق المصيدة و`exit 1` لا تُطلقها، وكذلك
#    `if ! cmd; then exit 1; fi`). وكلُّ بوّابةٍ في هذا الملفّ تفشل بـ`exit 1`:
#    الترحيلُ، وصحّةُ الخلفيّة، ورمزُ الواجهة، ونسختُها. فكانت تخرج **بلا
#    تراجع**: حاوياتُ «الاستبدال» الجديدة تبقى تخدم الطلبات على قاعدةٍ نصفِ
#    مُرحَّلة، ولا يُطبع أمرُ التراجع لأنّ الملخّص لم يُبلَغ — فيبدو الأمرُ
#    نشرةً فاشلةً نظيفة وهو خادمٌ عالق.
#
#    ومصيدةٌ على EXIT تمسك الاثنين معاً — الفشلَ الحقيقيَّ و`exit` الصريح —
#    بلا مطاردة كلّ بوّابةٍ على حدة اليوم وغداً. و`exit "$rc"` آخرُ أمرٍ فيها
#    فيبقى الخروجُ الصفريُّ صفريّاً رغم أنّ `[ ]` قبله تعود 1.
arm_rollback() { trap 'rc=$?; [ "$rc" -ne 0 ] && rollback; exit "$rc"' EXIT; }

# ── 0. البيئة ────────────────────────────────────────────────────
[ -f .env ] || { fail ".env غائب — الأسرار تُكتب باليد على الخادم فقط"; exit 1; }
set -a; . ./.env; set +a
for v in JWT_SECRET MASTER_KEY PLATFORM_AI_KEY DB_PASSWORD APP_DB_PASSWORD; do
  [ -n "${!v:-}" ] || { fail "$v غائبٌ من .env — لا إقلاع بسرٍّ ناقص"; exit 1; }
done

# ── 1. نسخة احتياطيّة قبل أيّ لمس ────────────────────────────────
say "نسخة احتياطيّة"
mkdir -p "$BACKUP_DIR"
BK="${BACKUP_DIR}/db-${STAMP}.sql.gz"
# 🔴 `< /dev/null` على كلّ `docker compose exec -T` لا يحتاج إدخالاً: الراية `-T`
#    تمرّر stdin إلى الحاوية و**تستهلكه كلّه**. فهذا السطر بلاها يأكل بقيّة
#    السكربت لو شُغِّل بـ`bash -s < deploy.sh` أو من حلقةٍ تقرأ من stdin —
#    فيُنشر نصفُ السكربت ويُعلَن النجاح. (يحرسه apps/worker/test/ops-scripts.)
docker compose exec -T db pg_dump -U "${DB_USER}" "${DB_NAME:-aibot}" < /dev/null | gzip > "$BK"
# فشل pg_dump الصامت يُنتج ملفّاً ضئيلاً. بلا هذا الفحص تنشر فوق حالةٍ لا تُستعاد.
SZ=$(stat -c%s "$BK" 2>/dev/null || echo 0)
[ "$SZ" -gt 10000 ] || { fail "النسخة ${SZ} بايت فقط — pg_dump فشل صامتاً"; exit 1; }
echo "  ✔ ${BK} (${SZ} بايت)"
ls -t "${BACKUP_DIR}"/db-*.sql.gz | tail -n +15 | xargs -r rm -f

# ── 1ب. حزمةٌ مشفَّرة تُسحب خارج الخادم ─────────────────────────
# ★ اللقطة أعلاه تحمي من «ترحيلٌ أفسد جدولاً». وهي **لا تحمي من موت القرص**:
#   هي على نفس القرص، و`MASTER_KEY` في `.env` بجانبها. فلو مات القرص ضاعت
#   البيانات وضاع المفتاح، ولا تُفكّ نسخةٌ لو وُجدت. راجع 19-backup-and-restore.
#
# 🔴 ولا تُفشل النشر مهما حدث: النسخ الاحتياطيّ ليس بوّابة إصدار، وإسقاطُ
#    إصلاحٍ عاجلٍ لأنّ عبارة مرورٍ غير مضبوطة عقوبةٌ في المكان الخطأ. لكنّه
#    يصرخ — ويُعاد الصراخ في الملخّص الأخير، لأنّ تحذيراً في السطر ٣٠ من
#    مخرَجٍ طويل لا يراه أحد.
OFFSITE_NOTE="لم تُنشأ"
if [ -x ops/backup-offsite.sh ]; then
  say "حزمةٌ مشفَّرة خارج الخادم"
  # ★ عبارة المرور تعيش في ملفّ المؤقّت، والنشر لا يرثها.
  #
  #   بلا هذا السطر تُنشأ الحزم اليوميّة وحدها، **وتسقط بالضبط الحزمةُ الأثمن**:
  #   التي تسبق تغييراً خطراً بثوانٍ. وأوّل نشرةٍ بعد بناء النظام أثبتت ذلك —
  #   قالت «الحزمة: لم تُنشأ» وتابعت.
  [ -z "${BACKUP_PASSPHRASE:-}" ] && [ -r "${HOME}/.config/aibot/backup.env" ] \
    && . "${HOME}/.config/aibot/backup.env"
  export BACKUP_PASSPHRASE
  OFF_LOG="${BACKUP_DIR}/offsite-${STAMP}.log"
  if ops/backup-offsite.sh > "$OFF_LOG" 2>&1; then
    OFFSITE_NOTE="$(grep -o 'aibot-[0-9]\{8\}-[0-9]\{6\}\.tar\.gz\.gpg' "$OFF_LOG" | head -1)"
    echo "  ✔ ${OFFSITE_NOTE}"
    rm -f "$OFF_LOG"
  else
    OFFSITE_NOTE="فشلت — راجع ${OFF_LOG}"
    {
      echo "⚠ ⚠ ⚠  الحزمة المشفَّرة لم تُنشأ. النشر يتابع، والخطرُ يبقى:"
      echo "        نسخُك كلّها على هذا القرص وحده، والمفتاح معها."
      echo "        السبب في: ${OFF_LOG}"
      echo "        الأرجح: BACKUP_PASSPHRASE غير مضبوطة — ops/install-backup-timer.sh"
    } >&2
  fi
fi

# ── 2. الشيفرة — pull فقط ────────────────────────────────────────
# 🔴 git reset --hard ممنوع: يحذف docker-compose.override.yml فتُنشئ Docker
#    volumes جديدةً فارغة بدل ربط الأصلية = فقدانٌ كامل للبيانات.
say "سحب الشيفرة (master)"
BEFORE="$(git rev-parse HEAD)"
git pull origin master
AFTER="$(git rev-parse HEAD)"
export GIT_REV="$AFTER"

# ── 2ب. السكربت يُحدّث نفسه فيجب أن يُعيد قراءتها ────────────────
# 🔴 علّةٌ صامتة كلّفت ترحيلَين: bash يقرأ السكربت على دفعات، فحين يسحب
#    git pull نسخةً جديدة تكون كتلةُ الترحيل (أسفل) قد قُرئت من النسخة
#    القديمة. فيُنفَّذ ترحيلُ الأمس ويُعلَن «تمّ» بصدق — عن ترحيلٍ ليس فيه
#    ما أُضيف. لا خطأ ولا تحذير ولا أثر.
if [ "$BEFORE" != "$AFTER" ] && [ "${AIBOT_REEXEC:-0}" != "1" ]; then
  if ! git diff --quiet "$BEFORE" "$AFTER" -- deploy.sh; then
    say "deploy.sh تغيّر — إعادة تنفيذ نفسه مرّةً واحدة"
    # و`EXIT` معها احتياطاً: `exec` يستبدل الصورة فلا تعمل المصائد، والنزعُ
    # الصريحُ يبقى صحيحاً لو صار الاستبدالُ يوماً استدعاءً عاديّاً.
    trap - ERR EXIT
    AIBOT_REEXEC=1 exec bash "$0" "$@"
  fi
fi

# ── 2ج. بوّابةُ الجودة — **قبل أن يُلمس شيء** ────────────────────
# 🔴 الإنتاج يشغّل **مصادر TypeScript** عبر `tsx`، و`tsx` يُسقط الأنواع ولا
#    يفحصها. فخطأُ نوعٍ لا يظهر في البناء ولا في الإقلاع: يظهر عند أوّل
#    استدعاءٍ لتلك الدالّة، على زبونٍ حقيقيّ، بعد النشر بساعات. ولا CI في
#    المستودع، فـ`deploy.sh` يسحب master ويبني ما فيه أيّاً كان.
#
# ★ وموضعُها هنا قرارٌ لا ترتيب: **قبل** وسم الصور و`arm_rollback`. فالفشلُ
#   هنا لا يحتاج تراجعاً أصلاً — لم يُبنَ شيءٌ ولم يُستبدل شيء، والحاوياتُ
#   العاملة لم تُمسّ. أمّا بوّابةٌ بعد الاستبدال فتُصلح بالتراجع ما كان يمكن
#   ألّا يقع. وأرخصُ عطلٍ ما لم يقع.
#
# ⚠️ والتبعيّاتُ تُثبَّت إن تغيّر القفل: `node_modules` على المضيف تبقى من
#    نشرةٍ سابقة، فحزمةٌ أُضيفت في master تجعل الاختبارات تفشل على غيابها لا
#    على عطلٍ حقيقيّ — إنذارٌ كاذبٌ يُعلّم الناسَ تخطّي البوّابة.
if [ "${AIBOT_SKIP_GATE:-0}" = "1" ]; then
  echo "  ⚠⚠ بوّابةُ الجودة **متخطّاة** بطلبٍ صريح (AIBOT_SKIP_GATE=1)"
  echo "     يُنشر بلا فحصِ أنواعٍ ولا اختبار. أعِدها فور انتهاء الطارئ."
else
  say "بوّابة الجودة"

  # ★★★ **بوّابةٌ تتعلّق أسوأ من بوّابةٍ غائبة** — وهذا وقع فعلاً.
  #
  #    أوّلُ نشرةٍ بعد تغيير القفل علّقت **عشرين دقيقة** على
  #    `pnpm install`: لا شبكة، ولا كتابةٌ على القرص، ولا رسالة. والنشرُ
  #    ينتظر إلى الأبد بلا مهلةٍ ولا تشخيص. وبوّابةٌ غائبةٌ تُنتج نشرةً
  #    مكسورة تُكتشف؛ أمّا بوّابةٌ معلّقةٌ فتُنتج مشغّلاً ينتظر شاشةً صامتة
  #    ثمّ يتعلّم أن يضبط `AIBOT_SKIP_GATE=1`.
  #
  # ⚠️ و`< /dev/null` على كلّ أمرٍ ينتظر: القاعدةُ مكتوبةٌ في هذا المستودع
  #    لـ`docker compose exec -T` («كلُّ نداءٍ يعلن مصدر stdin»)، وقد أدخلتُ
  #    أوامرَ تقرأ stdin بلا إعلانه. و`fd 0` للعمليّة المعلّقة كان أنبوباً
  #    موروثاً من `ssh`، وأداةٌ تسأل سؤالاً على أنبوبٍ لا يُغذّى تنتظر أبداً.
  #
  # ⚠️ والمهلةُ سخيّةٌ عمداً: الخادمُ مشتركٌ وحِملُه يبلغ سبعة، وبوّابةٌ تفشل
  #    على بطءٍ عابرٍ إنذارٌ كاذبٌ يُعلَّم أن يُتجاوَز.
  GATE_INSTALL_TIMEOUT="${GATE_INSTALL_TIMEOUT:-900}"
  GATE_STEP_TIMEOUT="${GATE_STEP_TIMEOUT:-600}"

  # ★ رسالةُ المهلة تُفرَّق عن رسالة الفشل: «تعلّق» و«فشل» عطلان مختلفان،
  #   وخلطُهما يُرسل المشخِّصَ في الاتّجاه الخاطئ. و124 رمزُ `timeout`.
  gate_run() {
    local secs="$1" what="$2"; shift 2
    local rc=0
    timeout "$secs" "$@" < /dev/null || rc=$?
    if [ "$rc" -eq 124 ]; then
      echo "  ✘ ${what}: تجاوز ${secs} ثانية فقُطع. ولم يُلمس شيءٌ بعد."
      echo "     شغّله يدويّاً على الخادم لترى أين يقف."
      exit 1
    fi
    return "$rc"
  }

  # ★★ **المقارنةُ بما هو مُثبَّتٌ فعلاً، لا بفرقٍ بين نسختَي git.**
  #    كان الشرطُ يسأل «هل تغيّر القفلُ في هذه السحبة؟» لا «هل يطابق
  #    المثبَّتُ القفلَ؟». فسحبةٌ فارغة — بعد نشرةٍ فشلت، أو سحبٍ يدويّ —
  #    تتخطّى التثبيتَ و`node_modules` قديمة. ووقع هذا: بقيت `xlsx@0.18.5`
  #    مثبَّتةً بينما القفلُ يقول 0.20.3، فأسقطت البوّابةُ نشرةً سليمة.
  #    والبصمةُ تُكتب **بعد** نجاح التثبيت وحده، فتثبيتٌ فاشلٌ يُعاد.
  LOCK_STAMP="node_modules/.aibot-lock-sha"
  LOCK_NOW="$(sha256sum pnpm-lock.yaml | cut -d" " -f1)"
  # ★ وأدواتُ البوّابة غائبةٌ = تثبيتٌ ناقص ولو طابقت البصمة (بصمةٌ كُتبت على
  #   تثبيتٍ حذف devDependencies — انظر أدناه).
  if [ ! -d node_modules ] || [ "$(cat "$LOCK_STAMP" 2>/dev/null)" != "$LOCK_NOW" ] \
     || [ ! -x node_modules/.bin/tsc ] || [ ! -x node_modules/.bin/vitest ]; then
    echo "  ℹ المثبَّت لا يطابق القفل — تثبيت التبعيّات"
    # ★★★ **`CI=true` — وبلاها كان التثبيت لا-عمليّةً صامتةً برمز نجاح.**
    #    pnpm يسأل تفاعليّاً حين يقرّر إعادةَ بناء `node_modules`:
    #      ? The modules directories will be removed and reinstalled
    #        from scratch. Proceed? (Y/n)
    #    ومع `< /dev/null` يصل EOF فيمضي **بلا تثبيت** ويُعيد صفراً. فتُكتب
    #    بصمةُ القفل على تثبيتٍ لم يقع، ويتخطّى النشرُ التالي التثبيتَ أصلاً.
    #    ووقع هذا: بقيت `xlsx@0.18.5` وسقط اختبارٌ يفحص المثبَّت.
    #    و`CI=true` هي الصيغةُ التي يفهمها pnpm للاعملٍ بلا سؤال.
    # ⚠️ ولا تُحذف `< /dev/null`: هي التي منعت الانتظارَ إلى الأبد قبل ذلك.
    #    الاثنتان معاً: لا سؤالَ يُطرح، ولو طُرح لم يُنتظر جوابُه.
    # 🔴 و`NODE_ENV=development` صراحةً: `.env` يضبطها `production` وقد حُمِّل
    #    أعلاه، وpnpm تحت `production` **يحذف** devDependencies — فذهبت typescript
    #    وvitest وtsx، ثمّ جلب `npx tsc` حزمةً أخرى اسمُها `tsc@2.0.4` (٢٦ أيلول).
    #    لم يظهر قبل ذلك لأنّ التثبيت لا يجري إلّا حين يتغيّر القفل.
    if ! NODE_ENV=development CI=true gate_run "$GATE_INSTALL_TIMEOUT" "تثبيت التبعيّات" \
         npx --yes pnpm@9 install --frozen-lockfile --prod=false; then
      echo "  ✘ فشل تثبيت التبعيّات — لا يُنشر. ولم يُلمس شيءٌ بعد."
      exit 1
    fi
    # ★ الأثرُ لا رمزُ الخروج: تثبيتٌ «ناجحٌ» بلا المُصرِّف هو ما وقع للتوّ.
    if [ ! -x node_modules/.bin/tsc ] || [ ! -x node_modules/.bin/vitest ]; then
      echo "  ✘ التثبيتُ نجح بلا typescript/vitest — أدواتُ البوّابة غائبة. لا يُنشر."
      exit 1
    fi
    printf '%s' "$LOCK_NOW" > "$LOCK_STAMP"
  fi

  # ① الأنواع: هذا ما لا يفحصه شيءٌ آخر في المسار كلِّه.
  for t in apps/api apps/worker apps/web packages/core packages/db \
           packages/shared packages/ai packages/channels packages/crypto; do
    [ -f "$t/tsconfig.json" ] || continue
    if ! gate_run "$GATE_STEP_TIMEOUT" "فحص أنواع ${t}" \
         npx --no-install tsc -p "$t/tsconfig.json" --noEmit; then
      echo "  ✘ خطأُ أنواعٍ في ${t} — لا يُنشر. ولم يُلمس شيءٌ بعد."
      exit 1
    fi
  done
  echo "  ✔ الأنواع سليمة"

  # ② الاختبارات — وأكثرُها حرّاسٌ ساكنةٌ تحرس أعطالاً وقعت فعلاً.
  if ! gate_run "$GATE_STEP_TIMEOUT" "الاختبارات" npx --no-install vitest run --reporter=basic; then
    echo "  ✘ اختبارٌ فاشل — لا يُنشر. ولم يُلمس شيءٌ بعد."
    exit 1
  fi
  echo "  ✔ الاختبارات تمرّ"

  # ③ إنذاراتُ الاعتماديّات — **تُقال ولا تُفشِل.**
  # ★ وموضعُها هنا لأنّ هذه البوّابةَ هي ما يقرّر فعلاً: CI يتخطّاها دفعٌ مباشرٌ
  #   إلى master، وهذه لا يتخطّاها شيء. وكانت عمياءَ تماماً عن الإنذارات.
  # ⚠️ و`|| true` مقصود: إنذارٌ في تبعيّةِ تطويرٍ لا يُبرّر منعَ إصلاحٍ عاجل،
  #    وإنذارٌ حقيقيٌّ يُعالَج بقرارٍ لا بحاجزٍ آليّ. والغرضُ أن **يُرى**.
  #    (ويحرس `ci-gate.test.ts` أن يبقى `exit 1` محصوراً بما يُفشِل فعلاً.)
  echo "  ℹ إنذارات الاعتماديّات:"
  timeout 120 npx --yes pnpm@9 audit --audit-level high < /dev/null 2>&1 \
    | grep -E "^│ (critical|high)" | sed 's/^/    /' || true
fi

